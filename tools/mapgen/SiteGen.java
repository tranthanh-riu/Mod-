import javax.imageio.ImageIO;
import java.awt.image.Raster;
import java.io.File;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.Arrays;
import java.util.List;
import java.util.Locale;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

/**
 * Places hand-made site builds (mcfunction files written for a flat floor at Y 96) onto the painted
 * Lands Between terrain. For each site it reads the terrain under the footprint, picks a floor height,
 * levels a foundation, clears hills above it, and rewrites every coordinate to its new position.
 *
 *   java tools/mapgen/SiteGen.java
 *
 * Run from the repository root. Output: the modpack datapack's functions/lands_between/limgrave/.
 */
public class SiteGen {
    static final String SRC = "src/main/resources/data/eldenring_core/functions/wave1/setup/";
    static final String OUT = "modpack/overrides/config/openloader/data/eldenring_worldgen/data/eldenring_core/functions/lands_between/limgrave/";
    static final String HEIGHT = "src/main/resources/eldenring_core_worldgen/height.png";
    static final String DIM = "eldenring_core:lands_between";
    static final String NS = "eldenring_core:lands_between/limgrave/";
    static final int SRC_FLOOR = 96;
    static final int MARGIN = 4;     // levelled apron around each footprint
    static final int CLEAR = 48;     // how far above the floor hills are cut away
    static final int FOUND = 24;     // how far below the floor gaps are filled

    /** A unit = several source files moved together. (sx,sz) in the source maps to (tx,tz) in the world. */
    record Unit(String name, String[] files, int sx, int sz, int tx, int tz, double percentile, String grace, int[] spawn) {}

    static final Unit[] UNITS = {
            // Southern plain of Limgrave: the starting headland, the Tree Sentinel field and the chapel.
            new Unit("gatefront", new String[]{"first_step", "sentinel_field", "elleh"},
                    0, 0, -470, 1560, 0.5, "The First Step", new int[]{-8, 2}),
            // The castle on the northern bluff: Margit's bridge, then Godrick's keep.
            new Unit("castle", new String[]{"stormveil_bridge", "stormveil_keep"},
                    105, 0, -430, 560, 0.75, null, null),
    };

    static Raster height;

    public static void main(String[] args) throws Exception {
        height = ImageIO.read(new File(HEIGHT)).getRaster();
        Files.createDirectories(Path.of(OUT));
        List<String> place = new ArrayList<>();
        List<int[]> areas = new ArrayList<>();
        StringBuilder report = new StringBuilder();

        for (Unit u : UNITS) {
            int[] box = null;
            List<String> body = new ArrayList<>();
            for (String f : u.files) {
                for (String line : Files.readAllLines(Path.of(SRC + f + ".mcfunction"), StandardCharsets.UTF_8)) {
                    body.add(line);
                    box = grow(box, line);
                }
            }
            int dx = u.tx - u.sx, dz = u.tz - u.sz;
            int x0 = box[0] + dx - MARGIN, x1 = box[1] + dx + MARGIN, z0 = box[4] + dz - MARGIN, z1 = box[5] + dz + MARGIN;
            int floor = floorY(x0, x1, z0, z1, u.percentile);
            int dy = floor - SRC_FLOOR;

            List<String> out = new ArrayList<>();
            out.add("# Generated by tools/mapgen/SiteGen.java from wave1/setup/" + String.join(", ", u.files) + ". Do not edit by hand.");
            out.add("# Foundation: fill gaps under the site, then cut away hills above it.");
            for (String fill : split(x0, x1, floor - FOUND, floor - 1, z0, z1)) {
                out.add("fill " + fill + " minecraft:stone replace #minecraft:replaceable");
                out.add("fill " + fill + " minecraft:stone replace minecraft:water");
            }
            out.add("fill " + x0 + " " + floor + " " + z0 + " " + x1 + " " + floor + " " + z1 + " minecraft:grass_block");
            for (String fill : split(x0, x1, floor + 1, floor + CLEAR, z0, z1)) out.add("fill " + fill + " minecraft:air");
            out.add("# Build.");
            for (String line : body) out.add(shift(line, dx, dy, dz));
            Files.write(Path.of(OUT + u.name + ".mcfunction"), out, StandardCharsets.UTF_8);

            place.add("function " + NS + u.name);
            areas.add(new int[]{x0, z0, x1, z1});
            report.append(String.format(Locale.ROOT, "%-10s floor Y=%d  area x %d..%d z %d..%d%n", u.name, floor, x0, x1, z0, z1));
        }

        // install / prepare / await / place / enter, same flow as wave1.
        StringBuilder fl = new StringBuilder(), loaded = new StringBuilder(), unload = new StringBuilder();
        for (int[] a : areas) {
            fl.append("forceload add ").append(a[0]).append(' ').append(a[1]).append(' ').append(a[2]).append(' ').append(a[3]).append('\n');
            unload.append("forceload remove ").append(a[0]).append(' ').append(a[1]).append(' ').append(a[2]).append(' ').append(a[3]).append('\n');
            for (int x = Math.floorDiv(a[0], 16) * 16; x <= a[2]; x += 16)
                for (int z = Math.floorDiv(a[1], 16) * 16; z <= a[3]; z += 16)
                    loaded.append(" if loaded ").append(x).append(" 64 ").append(z);
        }
        Unit start = UNITS[0];
        int[] sp = start.spawn;
        int spawnX = sp[0] - start.sx + start.tx, spawnZ = sp[1] - start.sz + start.tz;
        int spawnY = floorOf(start) + 1;

        write("install", List.of(
                "# Build the Limgrave sites into the Lands Between once (needs the modpack: Terralith + Open Loader).",
                "execute if data storage eldenring_core:limgrave built run tellraw @s {\"text\":\"Limgrave đã được dựng. Dùng /function " + NS + "enter để vào.\",\"color\":\"gold\"}",
                "execute unless data storage eldenring_core:limgrave built run tag @s[type=minecraft:player] add eldenring_core.limgrave_installer",
                "execute unless data storage eldenring_core:limgrave built in " + DIM + " run function " + NS + "prepare"));
        write("prepare", List.of(fl.toString().trim(),
                "schedule function " + NS + "await_chunks 2s replace"));
        write("await_chunks", List.of(
                "# Wait for every chunk under the sites before placing blocks.",
                "execute unless data storage eldenring_core:limgrave built in " + DIM + loaded + " run function " + NS + "place",
                "execute unless data storage eldenring_core:limgrave built run schedule function " + NS + "await_chunks 2s replace"));
        List<String> pl = new ArrayList<>(place);
        pl.add("data modify storage eldenring_core:limgrave built set value 1b");
        pl.add(unload.toString().trim());
        pl.add("tellraw @a[tag=eldenring_core.limgrave_installer] {\"text\":\"Limgrave đã sẵn sàng. Dùng /function " + NS + "enter để vào.\",\"color\":\"gold\"}");
        pl.add("tag @a[tag=eldenring_core.limgrave_installer] remove eldenring_core.limgrave_installer");
        write("place", pl);
        write("enter", List.of(
                "execute unless data storage eldenring_core:limgrave built run tellraw @s {\"text\":\"Hãy chạy /function " + NS + "install trước.\",\"color\":\"red\"}",
                String.format(Locale.ROOT, "execute if data storage eldenring_core:limgrave built in %s run tp @s[type=minecraft:player] %.1f %d %.1f -90 0",
                        DIM, spawnX + 0.5, spawnY, spawnZ + 0.5)));
        System.out.print(report);
        System.out.println("spawn " + spawnX + " " + spawnY + " " + spawnZ);
    }

    static int floorOf(Unit u) throws Exception {
        int[] box = null;
        for (String f : u.files)
            for (String line : Files.readAllLines(Path.of(SRC + f + ".mcfunction"), StandardCharsets.UTF_8)) box = grow(box, line);
        int dx = u.tx - u.sx, dz = u.tz - u.sz;
        return floorY(box[0] + dx - MARGIN, box[1] + dx + MARGIN, box[4] + dz - MARGIN, box[5] + dz + MARGIN, u.percentile);
    }

    static void write(String name, List<String> lines) throws Exception {
        Files.write(Path.of(OUT + name + ".mcfunction"), lines, StandardCharsets.UTF_8);
    }

    /** Terrain height percentile across the footprint, from the heightmap. */
    static int floorY(int x0, int x1, int z0, int z1, double pct) {
        List<Double> ys = new ArrayList<>();
        for (int x = x0; x <= x1; x += 2)
            for (int z = z0; z <= z1; z += 2) {
                int px = (x + 4096) / 4, pz = (z + 4096) / 4;
                ys.add(height.getSample(px, pz, 0) / 64.0 - 64);
            }
        Double[] a = ys.toArray(new Double[0]);
        Arrays.sort(a);
        return (int) Math.round(a[(int) Math.min(a.length - 1, a.length * pct)]);
    }

    static final Pattern FILL = Pattern.compile("^(fill) (-?\\d+) (-?\\d+) (-?\\d+) (-?\\d+) (-?\\d+) (-?\\d+)(.*)$");
    static final Pattern ONE = Pattern.compile("^(setblock|grace name) (-?\\d+) (-?\\d+) (-?\\d+)(.*)$");

    static int[] grow(int[] b, String line) {
        Matcher m = FILL.matcher(line);
        int[][] pts;
        if (m.matches()) {
            pts = new int[][]{{i(m, 2), i(m, 3), i(m, 4)}, {i(m, 5), i(m, 6), i(m, 7)}};
        } else {
            m = ONE.matcher(line);
            if (!m.matches()) return b;
            pts = new int[][]{{i(m, 2), i(m, 3), i(m, 4)}};
        }
        for (int[] p : pts) {
            if (b == null) b = new int[]{p[0], p[0], p[1], p[1], p[2], p[2]};
            b[0] = Math.min(b[0], p[0]); b[1] = Math.max(b[1], p[0]);
            b[2] = Math.min(b[2], p[1]); b[3] = Math.max(b[3], p[1]);
            b[4] = Math.min(b[4], p[2]); b[5] = Math.max(b[5], p[2]);
        }
        return b;
    }

    static String shift(String line, int dx, int dy, int dz) {
        Matcher m = FILL.matcher(line);
        if (m.matches()) {
            return String.format(Locale.ROOT, "fill %d %d %d %d %d %d%s", i(m, 2) + dx, i(m, 3) + dy, i(m, 4) + dz,
                    i(m, 5) + dx, i(m, 6) + dy, i(m, 7) + dz, m.group(8));
        }
        m = ONE.matcher(line);
        if (m.matches()) {
            return String.format(Locale.ROOT, "%s %d %d %d%s", m.group(1), i(m, 2) + dx, i(m, 3) + dy, i(m, 4) + dz, m.group(5));
        }
        if (line.startsWith("fill") || line.startsWith("setblock") || line.startsWith("grace") || line.startsWith("summon"))
            throw new IllegalStateException("Unhandled coordinate line: " + line);
        return line;
    }

    /** Splits a box into fills of at most 32768 blocks (vanilla limit), slicing along Y. */
    static List<String> split(int x0, int x1, int y0, int y1, int z0, int z1) {
        List<String> out = new ArrayList<>();
        int layer = (x1 - x0 + 1) * (z1 - z0 + 1);
        int step = Math.max(1, 32768 / layer);
        if (layer > 32768) throw new IllegalStateException("Footprint too large for one fill layer");
        for (int y = y0; y <= y1; y += step) {
            out.add(String.format(Locale.ROOT, "%d %d %d %d %d %d", x0, y, z0, x1, Math.min(y1, y + step - 1), z1));
        }
        return out;
    }

    static int i(Matcher m, int g) { return Integer.parseInt(m.group(g)); }
}
